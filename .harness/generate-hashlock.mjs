#!/usr/bin/env node
/**
 * Generate .harness/hashlock.json
 *
 * Run this ONCE after reviewing and approving all harness artifacts.
 * After running, the harness files are considered locked.
 * Any modification will cause runner.mjs to fail hash verification.
 *
 * Usage: node generate-hashlock.mjs
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

function sha256File(filePath) {
  const content = readFileSync(filePath);
  return createHash('sha256').update(content).digest('hex');
}

const EXCLUDE_DIRS = new Set(['node_modules']);
const EXCLUDE_FILES = new Set(['hashlock.json', 'package-lock.json']);

function collectFiles(dir, rootDir, results = []) {
  for (const entry of readdirSync(dir)) {
    if (EXCLUDE_DIRS.has(entry)) continue;
    const absPath = resolve(dir, entry);
    const stat = statSync(absPath);
    if (stat.isDirectory()) {
      collectFiles(absPath, rootDir, results);
    } else if (!EXCLUDE_FILES.has(entry)) {
      results.push(absPath);
    }
  }
  return results;
}

const harnessFiles = collectFiles(resolve(ROOT, '.harness'), ROOT);
const evalFiles = collectFiles(resolve(ROOT, 'evals'), ROOT);

const allFiles = [...harnessFiles, ...evalFiles];

const files = {};
for (const absPath of allFiles.sort()) {
  const relPath = relative(ROOT, absPath).replace(/\\/g, '/');
  files[relPath] = sha256File(absPath);
  console.log(`  ${relPath}`);
}

const lock = {
  files,
  generated: new Date().toISOString(),
  note: 'Generated by generate-hashlock.mjs after human review and approval of harness artifacts.',
};

const lockPath = resolve(__dirname, 'hashlock.json');
writeFileSync(lockPath, JSON.stringify(lock, null, 2));
console.log(`\nHashlock written to .harness/hashlock.json (${allFiles.length} files)`);
console.log('Harness is now locked. Do not modify harness or eval files.');
